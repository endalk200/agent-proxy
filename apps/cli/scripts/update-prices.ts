/**
 * Regenerates `src/usage/price-table.ts` from models.dev: every Anthropic and
 * OpenAI model's base price per million tokens, for equivalent cost. The
 * daemon never fetches prices itself; the owner runs this when prices or
 * models change, and commits the result:
 *
 *     bun apps/cli/scripts/update-prices.ts
 */

import { writeFileSync } from "node:fs"
import { join } from "node:path"

const SOURCE = "https://models.dev/api.json"
const PROVIDERS = ["anthropic", "openai"] as const

const response = await fetch(SOURCE)
if (!response.ok) throw new Error(`${SOURCE} answered HTTP ${response.status}`)
const asRecord = (value: unknown): Readonly<Record<string, unknown>> =>
  typeof value === "object" && value !== null ? Object.fromEntries(Object.entries(value)) : {}
const asNumber = (value: unknown) => (typeof value === "number" ? value : undefined)
const catalog = asRecord(await response.json())

/** `cost`'s rates as source fields, or none without an input and output rate. */
const ratesOf = (cost: Readonly<Record<string, unknown>>) => {
  const input = asNumber(cost["input"])
  const output = asNumber(cost["output"])
  const cacheRead = asNumber(cost["cache_read"])
  const cacheWrite = asNumber(cost["cache_write"])
  if (input === undefined || output === undefined) return undefined
  return [
    `input: ${input}`,
    `output: ${output}`,
    ...(cacheRead === undefined ? [] : [`cacheRead: ${cacheRead}`]),
    ...(cacheWrite === undefined ? [] : [`cacheWrite: ${cacheWrite}`]),
  ]
}

const rows: Array<string> = []
for (const provider of PROVIDERS) {
  const models = asRecord(asRecord(catalog[provider])["models"])
  for (const id of Object.keys(models).toSorted()) {
    const cost = asRecord(asRecord(models[id])["cost"])
    const fields = ratesOf(cost)
    if (fields === undefined) continue
    // Long-context tiers: models.dev's `tiers` of type `context`, priced over `size` input tokens.
    const tiers = (Array.isArray(cost["tiers"]) ? cost["tiers"] : []).flatMap((value) => {
      const tier = asRecord(value)
      const kind = asRecord(tier["tier"])
      const size = asNumber(kind["size"])
      const rates = ratesOf(tier)
      return kind["type"] === "context" && size !== undefined && rates !== undefined
        ? [`{ over: ${size}, ${rates.join(", ")} }`]
        : []
    })
    if (tiers.length > 0) fields.push(`tiers: [${tiers.join(", ")}]`)
    rows.push(`  ${JSON.stringify(id)}: { ${fields.join(", ")} },`)
  }
}

const file = join(import.meta.dirname, "..", "src", "usage", "price-table.ts")
writeFileSync(
  file,
  `// Generated by \`bun apps/cli/scripts/update-prices.ts\` from ${SOURCE} on ${new Date().toISOString().slice(0, 10)}.
// Do not edit by hand: run the script again.

import type { Price } from "./prices.ts"

/** USD prices per million tokens, by model id, with their long-context tiers. */
export const priceTable: Readonly<Record<string, Price>> = {
${rows.join("\n")}
}
`,
)
console.log(`Wrote ${rows.length} prices to ${file}`)
