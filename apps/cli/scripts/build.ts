#!/usr/bin/env bun
/**
 * Builds the CLI into one self-contained executable, `dist/agent-proxy`
 * (ADR-0008), which needs no Bun to run.
 *
 * Bun can embed files only by importing them, so this writes an entry point
 * that imports every file of the web client's build (`apps/web/dist`) as an
 * embedded file, bakes in the checkout's commit, and hands both to the same
 * `runProcess` that `src/bin.ts` runs from source. `bun build --compile`
 * then compiles that entry point.
 */
import { spawnSync } from "node:child_process"
import { mkdirSync, readdirSync, rmSync, statSync, writeFileSync } from "node:fs"
import { join, relative } from "node:path"

const cliDir = join(import.meta.dir, "..")
const webDist = join(cliDir, "..", "web", "dist")
const dist = join(cliDir, "dist")
const entryDir = join(dist, ".entry")
const output = join(dist, "agent-proxy")

const fail = (message: string): never => {
  console.error(`build: ${message}`)
  process.exit(1)
}

/** Every file under `dir`, as paths relative to it with `/` separators, in a stable order. */
const filesUnder = (dir: string): Array<string> =>
  readdirSync(dir, { recursive: true, encoding: "utf8" })
    .filter((name) => statSync(join(dir, name)).isFile())
    .map((name) => name.split("\\").join("/"))
    .toSorted()

const git = (args: ReadonlyArray<string>) => {
  const result = spawnSync("git", args, { cwd: cliDir, encoding: "utf8" })
  return result.status === 0 ? result.stdout.trim() : undefined
}

let web: Array<string> = []
try {
  web = filesUnder(webDist)
} catch {
  // Reported below.
}
if (!web.includes("index.html")) {
  fail(
    `the web client is not built (no ${join(webDist, "index.html")}); run \`bun run build\` at the repo root`,
  )
}

// The build names the commit it was made from, and says when the tree had
// uncommitted changes, so `--version`, `daemon status` and the dashboard name
// the exact build that runs.
const commit = git(["rev-parse", "--short=12", "HEAD"]) ?? "unknown"
const dirty = (git(["status", "--porcelain"]) ?? "") !== ""

rmSync(dist, { recursive: true, force: true })
mkdirSync(entryDir, { recursive: true })
const importPath = (file: string) => relative(entryDir, file).split("\\").join("/")
const entry = `// Generated by scripts/build.ts; not checked in.
import { runProcess } from ${JSON.stringify(importPath(join(cliDir, "src", "entry.ts")))}
import { RuntimeInfo } from ${JSON.stringify(importPath(join(cliDir, "src", "runtime-info.ts")))}
${web.map((file, index) => `import web${index} from ${JSON.stringify(importPath(join(webDist, file)))} with { type: "file" }`).join("\n")}

runProcess({
  runtimeInfo: RuntimeInfo.layerCompiled(${JSON.stringify({ commit, dirty })}),
  // The compiled binary is its own executable: it runs again with no script.
  self: { command: process.execPath, args: [] },
  dashboard: {
    _tag: "Embedded",
    files: {
${web.map((file, index) => `      ${JSON.stringify(file)}: web${index},`).join("\n")}
    },
  },
})
`
const entryFile = join(entryDir, "entry.ts")
writeFileSync(entryFile, entry)

const compiled = spawnSync("bun", ["build", "--compile", entryFile, "--outfile", output], {
  cwd: cliDir,
  stdio: "inherit",
})
rmSync(entryDir, { recursive: true, force: true })
if (compiled.status !== 0) fail("bun build --compile failed")
console.log(`build: ${relative(process.cwd(), output)} (${commit}${dirty ? "-dirty" : ""})`)
